# ==============================================================================
# 3. IFI 等级划分配置
# ==============================================================================
#
# IFI_LEVELS 用于将 IFI 综合肥力指数划分为不同等级。
#
# breaks 为等级边界，共有 6 个边界点，因此可以划分为 5 个等级。
#
# 当前区间为：
#
#   (-Inf, 0.3]   极低
#   (0.3, 0.5]    低
#   (0.5, 0.7]    中
#   (0.7, 0.9]    高
#   (0.9, Inf)    极高
#
# breaks 中的：
#   -Inf 表示负无穷
#   Inf  表示正无穷
#
# labels 中的等级名称必须与 breaks 划分出的区间数量一致。
#
# ==============================================================================

IFI_LEVELS <- list(
  
  # IFI 指数的等级分界点
  breaks = c(
    -Inf,  # 小于等于 0.3 的下限边界
    0.3,   # 极低与低之间的分界点
    0.5,   # 低与中之间的分界点
    0.7,   # 中与高之间的分界点
    0.9,   # 高与极高之间的分界点
    Inf    # 极高等级的上限边界
  ),
  
  # 各个 IFI 等级的名称
  labels = c(
    "极低",
    "低",
    "中",
    "高",
    "极高"
  )
)